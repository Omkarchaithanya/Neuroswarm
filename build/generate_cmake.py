#!/usr/bin/env python3
"""Generate optimized llama.cpp CMake command from detected CPU features."""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

_ROOT = Path(__file__).resolve().parents[1]
if str(_ROOT) not in sys.path:
    sys.path.insert(0, str(_ROOT))

from neuroswarm_arm.runtime.dipa.control.hardware_detector import (  # noqa: E402
    ControlHardwareDetector,
)


TEMPLATE = """# Auto-generated by build/generate_cmake.py — do not hand-edit.
# Host arch: {arch}
# Features: {features}

cmake_minimum_required(VERSION 3.16)
# Configure llama.cpp (run from llama.cpp source tree):
#   cmake -B build -C {cache_file} ..
#   cmake --build build --config Release -j

set(CMAKE_BUILD_TYPE Release CACHE STRING "" FORCE)
set(GGML_CPU_KLEIDIAI ON CACHE BOOL "" FORCE)
set(GGML_NATIVE ON CACHE BOOL "" FORCE)
set(GGML_OPENMP ON CACHE BOOL "" FORCE)
set(GGML_CPU_ALL_VARIANTS {all_variants} CACHE BOOL "" FORCE)
set(GGML_BLAS OFF CACHE BOOL "" FORCE)
set(GGML_CUDA OFF CACHE BOOL "" FORCE)
set(GGML_METAL OFF CACHE BOOL "" FORCE)
set(BUILD_SHARED_LIBS OFF CACHE BOOL "" FORCE)
"""


def pick_compiler() -> tuple[str, str]:
    clang = shutil.which("clang")
    clangxx = shutil.which("clang++")
    if clang and clangxx:
        return clang, clangxx
    cc = shutil.which("gcc") or "cc"
    cxx = shutil.which("g++") or "c++"
    return cc, cxx


def cmake_cli(profile: dict, *, source_dir: str = ".") -> list[str]:
    cc, cxx = pick_compiler()
    feats = profile.get("features") or {}
    args = [
        "cmake",
        "-B",
        "build",
        "-S",
        source_dir,
        f"-DCMAKE_C_COMPILER={cc}",
        f"-DCMAKE_CXX_COMPILER={cxx}",
        "-DCMAKE_BUILD_TYPE=Release",
        "-DGGML_CPU_KLEIDIAI=ON",
        "-DGGML_NATIVE=ON",
        "-DGGML_OPENMP=ON",
        "-DGGML_BLAS=OFF",
        "-DGGML_CUDA=OFF",
        "-DGGML_METAL=OFF",
    ]
    # Prefer runtime detection; ALL_VARIANTS helps multi-SKU images.
    if feats.get("sve2") or feats.get("i8mm") or feats.get("dotprod"):
        args.append("-DGGML_CPU_ALL_VARIANTS=ON")
    return args


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate KleidiAI CMake for llama.cpp")
    parser.add_argument("--profile", type=Path, help="CPU profile JSON from detect_cpu.py")
    parser.add_argument(
        "--cache-out",
        type=Path,
        default=Path("build/cmake/LlamaCppKleidiAI.cmake"),
        help="Write CMake initial cache file",
    )
    parser.add_argument("--print-cli", action="store_true", help="Print cmake CLI")
    parser.add_argument("--source-dir", default=".", help="llama.cpp source dir for CLI")
    args = parser.parse_args(argv)

    if args.profile and args.profile.exists():
        profile = json.loads(args.profile.read_text(encoding="utf-8"))
    else:
        profile = ControlHardwareDetector().detect().to_dict()

    feats = profile.get("features") or {}
    feat_str = ",".join(k for k, v in sorted(feats.items()) if v) or "none"
    all_variants = "ON" if any(feats.get(k) for k in ("sve2", "i8mm", "dotprod", "sme")) else "OFF"
    cache_path = args.cache_out
    cache_path.parent.mkdir(parents=True, exist_ok=True)
    body = TEMPLATE.format(
        arch=profile.get("arch", "unknown"),
        features=feat_str,
        all_variants=all_variants,
        cache_file=str(cache_path).replace("\\", "/"),
    )
    cache_path.write_text(body, encoding="utf-8")

    # Also copy/update template companion
    tmpl = Path(__file__).parent / "cmake" / "GenerateLlamaCpp.cmake.in"
    tmpl.parent.mkdir(parents=True, exist_ok=True)
    if not tmpl.exists():
        tmpl.write_text(TEMPLATE, encoding="utf-8")

    cli = cmake_cli(profile, source_dir=args.source_dir)
    meta = {
        "profile": profile,
        "cmake_cli": cli,
        "cache_file": str(cache_path),
        "verify_hint": "load_tensors: CPU_KLEIDIAI model buffer size",
        "sme_env": "GGML_KLEIDIAI_SME unset=auto, 0=off, >0=force",
    }
    meta_path = cache_path.with_suffix(".json")
    meta_path.write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")
    if args.print_cli:
        print(" ".join(cli))
    else:
        print(json.dumps({"cache": str(cache_path), "cli": cli}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
